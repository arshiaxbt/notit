// Reads footage/timeline.json, mirrors the plates into public/footage/ and writes src/footage.ts:
// the one mapping from clip names to files, event frames and the facts the film prints.
import {execFileSync} from 'node:child_process';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(path.join(root, 'footage/timeline.json'), 'utf8'));
mkdirSync(path.join(root, 'public/footage'), {recursive: true});

// Event name (as the recorder wrote it) → short key used by the scenes.
const KEYS = [
  [/pointer down on "Play as guest"/, 'click'],
  [/step: 3\/5/, 'step3'],
  [/step: 4\/5/, 'step4'],
  [/step: 5\/5/, 'step5'],
  [/signed in/, 'done'],
  [/pointer down on "I'll do it"/, 'click'],
  [/"Sending" appears/, 'sending'],
  [/confirmed/, 'confirmed'],
  [/round closes/, 'close'],
  [/coins start/, 'coins'],
  [/coins end/, 'coinsEnd'],
  [/pointer rests on the lock line/, 'lock'],
  [/pointer down on the Rules tab/, 'rules'],
  [/pointer rests on rule 5/, 'rule5'],
  [/pointer down on the crowd-size slider/, 'dragStart'],
  [/pointer up/, 'dragEnd'],
];
const clips = {};
for (const c of t.clips) {
  const name = c.file.replace(/\.mp4$/, '');
  // The plates are untagged H.264 whose pixels were written with the BT.601 matrix (the stage decodes to
  // #ffd509 as 601 and to #ffcd00 as 709). An untagged HD file is decoded as 709, which turns the yellow orange
  // beside the motion graphics. So the copy the film reads is converted to BT.709 and tagged as such.
  execFileSync(
    'npx',
    ['remotion', 'ffmpeg', '-y', '-loglevel', 'error', '-i', path.join(root, 'footage', c.file), '-vf', 'scale=in_color_matrix=bt601:out_color_matrix=bt709,format=yuv420p', '-c:v', 'libx264', '-crf', '10', '-preset', 'fast', '-g', '30', '-colorspace', 'bt709', '-color_primaries', 'bt709', '-color_trc', 'iec61966-2-1', '-color_range', 'tv', '-an', path.join(root, 'public/footage', c.file)],
    {cwd: root, stdio: 'inherit'},
  );
  const ev = {};
  for (const e of c.events ?? []) {
    const k = KEYS.find(([re]) => re.test(e.name));
    if (k && ev[k[1]] === undefined) ev[k[1]] = e.frame;
  }
  clips[name] = {file: `footage/${c.file}`, w: c.width, h: c.height, dpr: c.width / c.pageSize.width, offset: 0, frames: c.frames, real: c.real, ev};
}
const r = t.facts.realSession;
const short = (a) => a.replace(/^(guest)-.*(.{6})(\.testnet)$/, '$1…$2$3');
const facts = {
  account: r.account,
  accountShort: short(r.account),
  contract: r.contracts.fast,
  roundWatch: r.rounds.watch,
  roundVolunteer: r.rounds.volunteer,
  roundUnsaved: r.rounds.unsaved,
  costAtClick: r.costShownAtClick,
  burned: r.burned,
  paid: r.paidToIt,
  balanceStart: r.balances.afterSignUp,
  balanceAfterVolunteer: r.balances.afterVolunteer,
  balanceAfterUnsaved: r.balances.afterUnsavedRound,
  txVolunteer: r.transactions.volunteer,
  confirmSeconds: t.facts.volunteer.confirmSeconds,
  payers: t.clips.find((c) => c.file === 'unsaved.mp4').facts.payers,
  keyMethods: r.keysAfterSignUp.keys[0].permission.FunctionCall.method_names,
  labFrom: t.clips.find((c) => c.file === 'lab.mp4').facts.from.reading,
  labTo: t.clips.find((c) => c.file === 'lab.mp4').facts.to.reading,
};
const out = `/**
 * GENERATED by scripts/gen-footage.mjs from footage/timeline.json (written ${t.writtenAt}). Do not edit.
 * Clip names → files, event frames (counted from the first frame of each clip) and the facts the film prints.
 */
export interface Clip {
  /** Path under public/. */
  file: string;
  /** Source pixels. */
  w: number;
  h: number;
  /** Source pixels per CSS pixel of the app (2 for the 2560×1440 plates of a 1280×720 page). */
  dpr: number;
  /** First frame of this clip inside the file, and its length. */
  offset: number;
  frames: number;
  /** A session on the locked testnet contract (true) or the site's in-browser simulation (false). */
  real: boolean;
  /** Event → frame inside the clip. */
  ev: Record<string, number>;
}

/** True while the film is built against placeholder footage; plates are then stamped. */
export const STANDIN = false;

export const CLIPS = ${JSON.stringify(clips, null, 2)} satisfies Record<string, Clip>;

export const FACTS = ${JSON.stringify(facts, null, 2)};
`;
writeFileSync(path.join(root, 'src/footage.ts'), out);
console.log('wrote src/footage.ts', Object.keys(clips).join(' '));
